#!/usr/bin/env node
/**
 * Synth MemstreamEc2 + MemstreamLambda and write CloudFormation YAML to infra/.
 * Source of truth: TypeScript under infra/cdk/. Do not hand-edit infra/*.yaml.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "yaml";
const { stringify, parse } = yaml;

const HERE = dirname(fileURLToPath(import.meta.url));
const CDK_ROOT = join(HERE, "..");
const REPO_INFRA = join(CDK_ROOT, "..");
const OUT = join(CDK_ROOT, "cdk.out");

const HEADER = `# GENERATED by \`npm run synth -w @memstream/infra\` — do not edit by hand.
# Source of truth: infra/cdk/ (TypeScript CDK). Re-run synth after changing stacks.
`;

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    cwd: CDK_ROOT,
    encoding: "utf-8",
    ...opts,
  });
  if (r.status !== 0) {
    console.error(r.stderr || r.stdout || `${cmd} failed`);
    process.exit(r.status ?? 1);
  }
  return r;
}

function exportStack(stackName, outFile) {
  run("npx", [
    "cdk",
    "synth",
    stackName,
    "--quiet",
    "--path-metadata",
    "false",
    "--version-reporting",
    "false",
    "-o",
    OUT,
  ]);
  const jsonPath = join(OUT, `${stackName}.template.json`);
  const template = JSON.parse(readFileSync(jsonPath, "utf-8"));
  // Drop CDK metadata noise for a cleaner committed template
  delete template.Rules;
  if (template.Resources) {
    for (const [id, res] of Object.entries(template.Resources)) {
      if (id.startsWith("CDKMetadata") || res.Type === "AWS::CDK::Metadata") {
        delete template.Resources[id];
      }
    }
  }
  delete template.Parameters?.BootstrapVersion;
  const yamlText = stringify(template, {
    lineWidth: 120,
    aliasDuplicateObjects: false,
  });
  const dest = join(REPO_INFRA, outFile);
  writeFileSync(dest, HEADER + yamlText, "utf-8");
  console.error(`Wrote ${dest}`);
}

mkdirSync(OUT, { recursive: true });
exportStack("MemstreamEc2", "ec2.yaml");
exportStack("MemstreamLambda", "lambda.yaml");

// Sanity: load back
for (const f of ["ec2.yaml", "lambda.yaml"]) {
  parse(readFileSync(join(REPO_INFRA, f), "utf-8"));
}
console.error("Synth OK");
